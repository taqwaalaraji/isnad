-- Briefs and evaluation runs are generated by the worker.
create function public.enqueue_brief()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.enqueue_job('generate_brief', jsonb_build_object('brief_id', new.id), 5);
  return new;
end;
$$;

create trigger briefs_enqueue
  after insert on public.briefs
  for each row execute function public.enqueue_brief();

create function public.enqueue_eval_run()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.enqueue_job('run_eval', jsonb_build_object('eval_run_id', new.id), 0);
  return new;
end;
$$;

create trigger eval_runs_enqueue
  after insert on public.eval_runs
  for each row execute function public.enqueue_eval_run();
